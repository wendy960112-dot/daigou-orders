type Rgb = [number, number, number];

function fillRect(pixels: Uint8Array, width: number, height: number, x: number, y: number, w: number, h: number, color: Rgb) {
  const x0 = Math.max(0, x);
  const y0 = Math.max(0, y);
  const x1 = Math.min(width, x + w);
  const y1 = Math.min(height, y + h);
  for (let py = y0; py < y1; py += 1) {
    for (let px = x0; px < x1; px += 1) {
      const index = (py * width + px) * 4;
      pixels[index] = color[0];
      pixels[index + 1] = color[1];
      pixels[index + 2] = color[2];
      pixels[index + 3] = 255;
    }
  }
}

function drawText(pixels: Uint8Array, width: number, height: number, text: string, x: number, y: number, color: Rgb, scale: number) {
  let cursor = x;
  for (const char of text.toUpperCase()) {
    const glyph = FONT[char] ?? FONT[" "];
    for (let row = 0; row < glyph.length; row += 1) {
      for (let col = 0; col < glyph[row].length; col += 1) {
        if (glyph[row][col] === "1") {
          fillRect(pixels, width, height, cursor + col * scale, y + row * scale, scale, scale, color);
        }
      }
    }
    cursor += 6 * scale;
  }
}

export function makeReceiptPng(options: { heading: string; lines: string[]; accent: Rgb }) {
  const width = 480;
  const height = 300;
  const pixels = new Uint8Array(width * height * 4);
  fillRect(pixels, width, height, 0, 0, width, height, [255, 253, 248]);
  fillRect(pixels, width, height, 0, 0, width, 78, options.accent);
  drawText(pixels, width, height, options.heading, 28, 26, [255, 253, 248], 4);
  options.lines.slice(0, 4).forEach((line, index) => {
    drawText(pixels, width, height, line, 28, 110 + index * 42, [29, 25, 22], 3);
  });

  const raw = Buffer.alloc((width * 4 + 1) * height);
  for (let y = 0; y < height; y += 1) {
    const rowStart = y * (width * 4 + 1);
    raw[rowStart] = 0;
    Buffer.from(pixels.buffer, pixels.byteOffset + y * width * 4, width * 4).copy(raw, rowStart + 1);
  }

  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8;
  ihdr[9] = 6;
  const signature = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]);
  return Buffer.concat([
    signature,
    chunk("IHDR", ihdr),
    chunk("IDAT", zlib.deflateSync(raw)),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}
